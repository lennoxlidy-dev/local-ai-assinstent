def strings(lang: str) -> dict[str, str]:
    i = 1 if lang == "de" else 0
    return {k: v[i] for k, v in _T.items()}


def text(key: str, lang: str, **kw: object) -> str:
    v = _T.get(key)
    s = (v[1] if lang == "de" else v[0]) if v else key
    return s.format(**kw) if kw else s


